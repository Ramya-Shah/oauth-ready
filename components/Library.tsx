"use client";
import Link from "next/link";
import { useState } from "react";
import { Difficulty } from "./bits";
import RouteBar, { hoursText, waitText } from "./RouteBar";
import { DIFFICULTY_RUBRIC, type DayRange } from "@/lib/schema";

type Item = {
  slug: string; name: string; origin: string; officialDomain: string; difficulty: number; wait: DayRange;
  topBlocker: string; effort: { min: number; max: number }; counts: Record<string, number>; reviewed: boolean;
};

const FILTERS = [
  { k: "all", t: "All apps" },
  { k: "fast", t: "No review wait" },
  { k: "review", t: "Needs a review" },
  { k: "hard", t: "Security assessment" },
];

function match(i: Item, f: string) {
  if (f === "fast") return i.wait !== "unknown" && i.wait.maxDays === 0;
  if (f === "review") return i.difficulty >= 3;
  if (f === "hard") return i.difficulty >= 5;
  return true;
}

function status(i: Item) {
  if (i.origin !== "curated") return "Generated by the agent";
  return i.reviewed ? "Reviewed against sources" : "Not yet reviewed";
}

function Row({ i }: { i: Item }) {
  const total = Object.values(i.counts).reduce((a, b) => a + b, 0);
  const strong = (i.counts.tested ?? 0) + (i.counts.sourced ?? 0);
  const noWait = i.wait !== "unknown" && i.wait.maxDays === 0;
  return (
    <Link href={`/guides/${i.slug}`} className="lib-row">
      <div className="lib-app">
        <span className="lib-name">{i.name}</span>
        <span className="lib-sub">{status(i)}</span>
      </div>
      <div className="lib-time">
        <span className="lib-verdict">
          {hoursText(i.effort)}, <span className={noWait ? "z" : "w"}>{waitText(i.wait).replace(/^then /, "")}</span>
        </span>
        <RouteBar effort={i.effort} wait={i.wait} size="small" />
      </div>
      <div className="lib-blocker">{i.topBlocker}</div>
      <div className="lib-ev">
        <span className="row" title={DIFFICULTY_RUBRIC[i.difficulty]}><Difficulty n={i.difficulty} /> {i.difficulty}/5</span>
        <span className="lib-sub">{strong} of {total} claims tested or from official docs</span>
      </div>
    </Link>
  );
}

export default function Library({ curated, generated }: { curated: Item[]; generated: Item[] }) {
  const [f, setF] = useState("all");
  const c = curated.filter((i) => match(i, f));
  const g = generated.filter((i) => match(i, f));
  return (
    <>
      <div className="chips" role="group" aria-label="Filter apps">
        {FILTERS.map((x) => (
          <button key={x.k} className={`chip ${f === x.k ? "on" : ""}`} aria-pressed={f === x.k} onClick={() => setF(x.k)}>{x.t}</button>
        ))}
      </div>
      <section aria-labelledby="lib-h">
        <div className="lib-head" aria-hidden>
          <span>App</span><span>Your work, then the wait (same scale for every app)</span><span>Most likely to stop you</span><span>Difficulty</span>
        </div>
        <h2 id="lib-h" className="sr-only">Library</h2>
        {c.map((i) => <Row key={i.slug} i={i} />)}
        {!c.length && <p className="muted">No library apps match this filter.</p>}
      </section>
      {g.length > 0 && (
        <section style={{ marginTop: 40 }}>
          <h2>Generated by the agent</h2>
          <p className="muted small" style={{ marginTop: 0 }}>Written live from the provider&apos;s docs and endpoint checks. Not reviewed by a person.</p>
          {g.map((i) => <Row key={i.slug} i={i} />)}
        </section>
      )}
    </>
  );
}
